W = lambda mult=1.0, **kw: {"type": "damage", "source": "weapon", "mult": mult, **kw}  # noqa: E731


def S(el, lo, hi, scale=0.8, **kw):
    return {"type": "damage", "source": "spell", "element": el, "base": [lo, hi], "scale": scale, **kw}


def ST(status, duration=2, chance=1.0, **kw):
    return {"type": "status", "status": status, "duration": duration, "chance": chance, **kw}


